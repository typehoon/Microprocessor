void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{

  if (htim->Instance == TIM6)
  {
	  HAL_ADC_Start(&hadc1);
	  if (HAL_ADC_PollForConversion(&hadc1, 1) == HAL_OK)
	      {
    // 1. ADC 값 읽기 및 1.5V 오프셋(2048) 제거
    uint32_t adc_raw = HAL_ADC_GetValue(&hadc1);
    double adc_val = (double)adc_raw - 2048.0;

    // 2. 필터 함수 호출
    // dac_res[0]에는 원본(Reference), dac_res[1]에는 필터링된 값이 담김
    microcontroller(&adc_val, dac_res);

    // 3. 출력 오프셋(2048) 재인가 및 범위 제한(Saturation)
    for (int i = 0; i < 2; i++)
    {
    	double out = 0;
    	if(i == 0){
    		out = dac_res[0] + 2048.0;
    	}
    	else {
    		out = dac_res[7] + 2048.0;
    	}
      if (out > 4095.0) out = 4095.0;
      if (out < 0.0)    out = 0.0;

      // DAC1_CH1(PA4)와 DAC1_CH2(PA5)로 각각 출력
      HAL_DAC_SetValue(&hdac1, (i == 0 ? DAC_CHANNEL_1 : DAC_CHANNEL_2),
                       DAC_ALIGN_12B_R, (uint32_t)out);
    }
	      }
  }
}
